$order = 1;
foreach ($curriculumData as $group) {
    $grade = $group['grade'];
    $subject = $group['subject'];
    foreach ($group['chapters'] as $chapter => $subTopics) {
        foreach ($subTopics as $subTopic) {
            mysqli_stmt_bind_param($insertStmt, "isssi", $grade, $subject, $chapter, $subTopic, $order);

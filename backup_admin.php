/**
 * Pure-PHP database backup (no shell_exec/mysqldump binary dependency -
 * many shared hosts and locked-down XAMPP installs disable shell_exec, so
 * this reads the schema/data over the existing mysqli connection instead).
 * Writes proper UTF-8 (not the UTF-16 issue found in the original
 * database.sql during the audit).
 */
function runBackup($conn, $dbName) {
    $output = "-- Backup of `$dbName` generated " . date('Y-m-d H:i:s') . "\n";
    $output .= "-- Generated by backup_admin.php (pure PHP, UTF-8)\n";
    $output .= "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS=0;\n\n";

    $tablesResult = mysqli_query($conn, "SHOW TABLES");
    $tables = [];
    while ($row = mysqli_fetch_row($tablesResult)) $tables[] = $row[0];

    foreach ($tables as $table) {
        $output .= "-- ----------------------------\n-- Table: $table\n-- ----------------------------\n";
        $createRow = mysqli_fetch_row(mysqli_query($conn, "SHOW CREATE TABLE `$table`"));
        $output .= "DROP TABLE IF EXISTS `$table`;\n" . $createRow[1] . ";\n\n";

        $dataResult = mysqli_query($conn, "SELECT * FROM `$table`");
        $rowCount = 0;
        while ($row = mysqli_fetch_assoc($dataResult)) {
            $cols = array_keys($row);
            $vals = array_map(function ($v) use ($conn) {
                if ($v === null) return 'NULL';
                return "'" . mysqli_real_escape_string($conn, $v) . "'";
            }, array_values($row));
            $output .= "INSERT INTO `$table` (`" . implode('`,`', $cols) . "`) VALUES (" . implode(',', $vals) . ");\n";
            $rowCount++;
            // Flush periodically to avoid building an enormous string in memory for huge tables
            if ($rowCount % 500 === 0 && !empty($GLOBALS['__backup_fh']) && is_resource($GLOBALS['__backup_fh'])) {
                fwrite($GLOBALS['__backup_fh'], $output);
                $output = '';
            }
        }
        $output .= "\n";
    }
    $output .= "SET FOREIGN_KEY_CHECKS=1;\n";
    return $output;
}


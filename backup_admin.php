        $safe = basename($_POST['filename'] ?? '');
        $path = __DIR__ . '/backups/' . $safe;
        if (preg_match('/^backup_\d{8}_\d{6}\.sql$/', $safe) && file_exists($path)) {
            unlink($path);
            auditLog($conn, 'database_backup_deleted', null, null, $safe);
            $message = "ምትኬ ተሰርዟል።";
        }
    }
}

